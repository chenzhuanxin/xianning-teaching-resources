def make_paper(idx):
    title, seed, term = SEEDS[idx]
    m = base("九年级物理", title,
             f"（北师大版　{term}　满分100分　时间90分钟）", fs=100, dur=90)
    p = []
    p.append({"name": "一、单项选择题（每题3分，共30分）", "questions": [
        Q(i, s, 3, opts=o, kind="选择")
        for i, (s, o, _, _) in enumerate(CHOICE[idx], 1)
    ]})
    p.append({"name": "二、填空题（每空2分，共20分）", "questions": [
        Q(11, t, 4, kind="填空", blanks=2)
        for i, t in enumerate(FILLS[idx]) if i < 5
    ]})
    p.append({"name": "三、计算题（共50分）", "questions": [
        Q(no, text, sc, kind="计算") for no, text, sc, _ in TEXT[idx]
    ]})

    answers = []
    for i, (_, _, ans, analy) in enumerate(CHOICE[idx], 1):
        answers.append(A(i, ans, analy))
    for i, v in enumerate(FILL_ANS[idx]):
        answers.append(A(11 + i, v, "注意单位与物理量的准确性。"))
    for no, _, _, ans in TEXT[idx]:
        answers.append(A(no, ans, "计算题要写出公式、代入数据、带单位，最后简洁作答。"))

    out.append(save(m, p, answers, seed))


