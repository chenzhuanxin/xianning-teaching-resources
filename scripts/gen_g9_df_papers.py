def make_paper(idx):
    title, seed, term = SEEDS[idx]
    m = base("九年级道德与法治", title,
             f"（统编版　{term}　满分100分　时间50分钟）", fs=100, dur=50)
    p = []
    p.append({"name": "一、单项选择题（每题2分，共40分）", "questions": [
        Q(i, s, 2, opts=o, kind="选择")
        for i, (s, o, _, _) in enumerate(CHOICE[idx], 1)
    ]})
    p.append({"name": "二、非选择题（共60分）", "questions": [
        Q(no, text, sc, kind="材料分析") for no, text, sc, _ in MATERIAL[idx]
    ]})

    answers = []
    for i, (_, _, ans, analy) in enumerate(CHOICE[idx], 1):
        answers.append(A(i, ans, analy))
    for no, _, _, ans in MATERIAL[idx]:
        answers.append(A(no, ans, "答案要求分点作答，使用学科术语，结合材料与所学知识。"))

    out.append(save(m, p, answers, seed))


if __name__ == "__main__":
    for i in range(5):
        make_paper(i)
    print("已生成 %d 套：" % len(out))
    for s in out:
        print(" -", s)
