    m = base("九年级化学", title,
             f"（人教版　{term}　满分100分　时间60分钟）", fs=100, dur=60)
    p = []
    p.append({"name": "一、单项选择题（每题2分，共20分）", "questions": [
        Q(i, s, 2, opts=o, kind="选择")
        for i, (s, o, _, _) in enumerate(CHOICE[idx], 1)
    ]})
    p.append({"name": "二、填空题（每空1分，共20分）", "questions": [
        Q(11, t, 4, kind="填空") for t in FILLS[idx]
    ]})
    p.append({"name": "三、非选择题（共60分）", "questions": [
        Q(no, text, sc, kind="综合") for no, text, sc, _ in TEXT[idx]
    ]})

