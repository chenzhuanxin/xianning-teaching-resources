    m = base("九年级数学", title,
             f"（人教版　{term}　满分120分　时间120分钟）", fs=120, dur=120)
    p = []
    p.append({"name": "一、选择题（每题3分，共30分）", "questions": [
        Q(i, stem, 3, opts=opts, kind="选择")
        for i, (stem, opts) in enumerate(CHOICES[idx], 1)
    ]})
    p.append({"name": "二、填空题（每题3分，共15分）", "questions": [
        Q(11 + i, t, 3, kind="填空") for i, t in enumerate(FILLS[idx])
    ]})
    p.append({"name": "三、解答题（共75分）", "questions": [
        Q(no, text, sc, kind=kind) for no, text, sc, kind in SOLVE[idx]
    ]})

    answers = []
    for i, opt in enumerate(CHOICE_ANS[idx], 1):
        answers.append(A(i, opt, "本题考查基础概念与运算，注意审题与计算准确性。"))
    for i, v in enumerate(FILL_ANS[idx]):
        answers.append(A(11 + i, v, "填空题注意结果的化简与取值范围。"))
    for i, v in enumerate(SOLVE_ANS[idx]):
        answers.append(A(16 + i, v, "解题步骤完整，注意书写规范与最终结论。"))

    out.append(save(m, p, answers, seed))


